/**
 * Tinted icon built on foundation [Image]. The vector is scaled to fit [size] keeping its aspect
 * ratio.
 */
@Composable
fun EqualIcon(
    imageVector: ImageVector,
    contentDescription: String?,
    tint: Color,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
) {
    Image(
        imageVector = imageVector,
        contentDescription = contentDescription,
        modifier = modifier.size(size),
        contentScale = ContentScale.Fit,
        colorFilter = ColorFilter.tint(tint),
    )
}

/** Default deterministic waveform samples (0..1). */
val DefaultWaveformSamples: List<Float> = listOf(
    0.3f, 0.5f, 0.8f, 0.6f, 0.9f, 0.4f, 0.7f, 1f, 0.5f, 0.3f,
    0.6f, 0.8f, 0.4f, 0.9f, 0.7f, 0.5f, 0.3f, 0.6f, 1f, 0.8f,
    0.4f, 0.6f, 0.9f, 0.5f, 0.7f, 0.3f, 0.5f, 0.8f, 0.6f, 0.4f,
)

/**
 * Voice-note waveform (SPEC §11): bars 2dp wide, gap 2dp, heights 4–16dp, centred vertically.
 * Bars before [progress] (0..1) use [playedColor]. A drawing, not an icon.
 */
@Composable
fun EqualWaveform(
    modifier: Modifier = Modifier,
    samples: List<Float> = DefaultWaveformSamples,
    progress: Float = 0f,
    barColor: Color = EqualTheme.colors.waveformBar,
    playedColor: Color = EqualTheme.colors.waveformBarPlayed,
) {
    Canvas(modifier = modifier) {
        if (samples.isEmpty()) return@Canvas
        val barWidth = 2.dp.toPx()
        val gap = 2.dp.toPx()
        val minH = 4.dp.toPx()
        val maxH = 16.dp.toPx()
        val count = ((size.width + gap) / (barWidth + gap)).toInt().coerceAtLeast(1)
        val clamped = progress.coerceIn(0f, 1f)
        for (i in 0 until count) {
            val sample = samples[(i * samples.size / count).coerceIn(0, samples.size - 1)].coerceIn(0f, 1f)
            val h = minH + (maxH - minH) * sample
            val x = i * (barWidth + gap)
            val played = (i + 0.5f) / count <= clamped
            drawRoundRect(
                color = if (played) playedColor else barColor,
                topLeft = Offset(x, (size.height - h) / 2f),
                size = Size(barWidth, h),
                cornerRadius = CornerRadius(barWidth / 2f, barWidth / 2f),
            )
        }
    }
}
