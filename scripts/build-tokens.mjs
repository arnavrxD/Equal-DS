#!/usr/bin/env node
// Equal AI Design System — token build.
// tokens/tokens.json is the single source of truth. This script emits:
//   web/src/tokens/tokens.css   CSS custom properties (light + dark) and type classes
//   web/src/tokens/tokens.ts    typed token object for JS/TS
//   compose/equal-ds/src/main/java/ai/equal/ds/tokens/EqualTokens.kt
// Never hand-edit the outputs.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'));

const HEADER = 'GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit.';

// ---------- helpers ----------
const prim = {};
for (const [group, values] of Object.entries(t.primitive)) {
  for (const [name, hex] of Object.entries(values)) prim[`${group}.${name}`] = hex.toUpperCase();
}
// A reference is a colour-guide colour at 100%, optionally with an opacity: "{brand.green}" or
// "{brand.green} @ 36%" (Figma's "Colours" set paints the same colours at x%). The opacity form
// resolves to rgba(…) so both web and Compose get the exact Figma value.
const REF = /^\{(.+?)\}(?:\s*@\s*(\d+(?:\.\d+)?)%)?$/;
const HEX_ALPHA = /^#([0-9A-Fa-f]{6})\s*@\s*(\d+(?:\.\d+)?)%$/;
const resolveRef = (v) => {
  const h = typeof v === 'string' ? HEX_ALPHA.exec(v) : null;
  if (h) {
    const [r, g, b] = [0, 2, 4].map((i) => parseInt(h[1].slice(i, i + 2), 16));
    return `rgba(${r},${g},${b},${+(parseFloat(h[2]) / 100).toFixed(3)})`;
  }
  const m = REF.exec(v);
  if (!m) return v;
  const hex = prim[m[1]];
  if (!hex) throw new Error(`Unknown primitive reference ${v}`);
  if (m[2] === undefined) return hex;
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
  return `rgba(${r},${g},${b},${+(parseFloat(m[2]) / 100).toFixed(3)})`;
};
const refLabel = (v) => {
  const m = REF.exec(v);
  return m ? m[1].replace('.', '/') + (m[2] !== undefined ? ` · ${m[2]}%` : '') : 'direct value';
};

// "component/chat-bubble/user-bg" -> "chat-bubble-user-bg"
const aliasSlug = (name) => name.replace(/^component\//, '').replace(/[/_]/g, '-');
const camel = (s) => s.replace(/[-/_\s]+(.)/g, (_, c) => c.toUpperCase()).replace(/^(.)/, (c) => c.toLowerCase());

const aliases = Object.entries(t.alias).map(([name, v]) => ({
  name,
  slug: aliasSlug(name),
  key: camel(aliasSlug(name)),
  light: resolveRef(v.light),
  dark: resolveRef(v.dark),
  lightRef: refLabel(v.light),
  darkRef: refLabel(v.dark),
  derived: !!(v.derived ?? v.proposed),
  why: v.why ?? null,
  group: name.startsWith('component/') ? 'component' : name.split('/')[0],
}));

// Gradient: [head, ...stops]. head is "180deg" (linear) or "radial RX% RY% at CX% CY%" (elliptical
// radial). A stop is "<colour> <position>%", where colour may be a reference with an opacity.
const splitStop = (s) => {
  const i = s.lastIndexOf(' ');
  return { color: resolveRef(s.slice(0, i).trim()), pos: parseFloat(s.slice(i + 1)) };
};
const resolveGradient = ([head, ...stops]) => [head, ...stops.map((s) => { const { color, pos } = splitStop(s); return `${color} ${pos}%`; })];
const gradients = Object.entries(t.gradient).map(([name, v]) => ({
  name,
  key: camel(name),
  light: resolveGradient(v.light),
  dark: resolveGradient(v.dark),
  derived: !!(v.derived ?? v.proposed),
  why: v.why ?? null,
}));
const cssGradient = ([head, ...stops]) =>
  head.startsWith('radial') ? `radial-gradient(${head.replace(/^radial\s*/, '')}, ${stops.join(', ')})` : `linear-gradient(${head}, ${stops.join(', ')})`;

const typeEntries = Object.entries(t.typography).filter(([k]) => !k.startsWith('$'));

// ---------- CSS ----------
let css = `/* ${HEADER} */\n\n`;
css += `@import '@fontsource/dm-sans/400.css';\n@import '@fontsource/dm-sans/500.css';\n@import '@fontsource/dm-sans/600.css';\n@import '@fontsource/dm-sans/700.css';\n@import '@fontsource/dm-sans/400-italic.css';\n\n`;
css += `:root {\n`;
css += `  --eq-font-family: '${t.typography.$fontFamily}', '${t.typography.$fallback}', system-ui, sans-serif;\n`;
for (const [k, hex] of Object.entries(prim)) css += `  --eq-${k.split('.')[1]}: ${hex};\n`;
for (const [k, v] of Object.entries(t.spacing)) css += `  --eq-space-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(t.radius)) css += `  --eq-radius-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(t.shadow)) css += `  --eq-shadow-${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}: ${v};\n`;
for (const [k, v] of Object.entries(t.motion.duration)) css += `  --eq-duration-${k}: ${v}ms;\n`;
for (const [k, v] of Object.entries(t.motion.easing)) css += `  --eq-easing-${k}: ${v};\n`;
css += `}\n\n`;

const themeBlock = (mode) => {
  let s = '';
  for (const a of aliases) s += `  --eq-${a.slug}: ${a[mode]};${a.derived ? ' /* derived */' : ''}\n`;
  for (const g of gradients) s += `  --eq-gradient-${g.name}: ${cssGradient(g[mode])};\n`;
  return s;
};
css += `:root,\n[data-theme='light'] {\n  color-scheme: light;\n${themeBlock('light')}}\n\n`;
css += `[data-theme='dark'] {\n  color-scheme: dark;\n${themeBlock('dark')}}\n\n`;

for (const [name, s] of typeEntries) {
  const kebab = name.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
  css += `.eq-t-${kebab} {\n  font-family: var(--eq-font-family);\n  font-size: ${s.size}px;\n  line-height: ${s.lineHeight}px;\n  font-weight: ${s.weight};\n  letter-spacing: ${s.tracking}em;\n`;
  if (s.italic) css += `  font-style: italic;\n`;
  if (s.uppercase) css += `  text-transform: uppercase;\n`;
  if (s.tabular) css += `  font-variant-numeric: tabular-nums;\n  font-feature-settings: 'tnum';\n`;
  css += `}\n`;
}
css += `\n/* Non-Latin strings reset tracking to 0em (Typography §05). */\n[lang]:not([lang^='en']) { letter-spacing: 0em; }\n.eq-non-latin { letter-spacing: 0em !important; }\n`;

// ---------- TS ----------
const ts = `// ${HEADER}

export const primitives = ${JSON.stringify(t.primitive, null, 2)} as const;

export type AliasToken = {
  name: string;
  cssVar: string;
  light: string;
  dark: string;
  lightRef: string;
  darkRef: string;
  group: string;
  /** Final value derived from the screens/references rather than the colour guide. */
  derived: boolean;
  why: string | null;
};

export const aliases: AliasToken[] = ${JSON.stringify(
  aliases.map((a) => ({
    name: a.name,
    cssVar: `--eq-${a.slug}`,
    light: a.light,
    dark: a.dark,
    lightRef: a.lightRef,
    darkRef: a.darkRef,
    group: a.group,
    derived: a.derived,
    why: a.why,
  })),
  null,
  2,
)};

/** CSS variable references for every alias token, e.g. color.textPrimary -> 'var(--eq-text-primary)'. */
export const color = {
${aliases.map((a) => `  ${a.key}: 'var(--eq-${a.slug})',`).join('\n')}
} as const;

export const gradients = ${JSON.stringify(
  gradients.map((g) => ({ name: g.name, cssVar: `--eq-gradient-${g.name}`, light: cssGradient(g.light), dark: cssGradient(g.dark), derived: g.derived, why: g.why })),
  null,
  2,
)};

export type TypeToken = { size: number; lineHeight: number; weight: 400 | 500 | 700; tracking: number; italic?: boolean; uppercase?: boolean; tabular?: boolean };
export const typography = ${JSON.stringify(Object.fromEntries(typeEntries), null, 2)} as const satisfies Record<string, TypeToken>;
export type TypeName = keyof typeof typography;

export const fontFamily = ${JSON.stringify(t.typography.$fontFamily)};
export const spacing = ${JSON.stringify(t.spacing)} as const;
export const radius = ${JSON.stringify(t.radius)} as const;
export const size = ${JSON.stringify(t.size)} as const;
export const shadow = ${JSON.stringify(t.shadow, null, 2)} as const;
export const motion = ${JSON.stringify(t.motion)} as const;
`;

// ---------- Kotlin ----------
const ktColor = (v) => {
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(v);
  if (rgba) {
    const [, r, g, b, a] = rgba;
    const hex = [Math.round(parseFloat(a) * 255), +r, +g, +b].map((n) => n.toString(16).padStart(2, '0')).join('').toUpperCase();
    return `Color(0x${hex})`;
  }
  return `Color(0xFF${v.replace('#', '').toUpperCase()})`;
};
const toRgba = (c) => {
  const m = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(c);
  if (m) return [+m[1], +m[2], +m[3], +m[4]];
  const h = c.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).concat(1);
};
const fromRgba = ([r, g, b, a]) => (a >= 0.999 ? '#' + [r, g, b].map((n) => Math.round(n).toString(16).padStart(2, '0')).join('').toUpperCase() : `rgba(${Math.round(r)},${Math.round(g)},${Math.round(b)},${+a.toFixed(3)})`);
const lerp = (c1, c2, t) => fromRgba(toRgba(c1).map((v, i) => v + (toRgba(c2)[i] - v) * t));
// Android needs stop positions inside 0..1: a stop outside is replaced by the colour at the edge.
const clampStops = (stops) => {
  const out = stops.map((s) => splitStop(s));
  const at = (p) => {
    for (let i = 0; i < out.length - 1; i++) if (p >= out[i].pos && p <= out[i + 1].pos) return lerp(out[i].color, out[i + 1].color, (p - out[i].pos) / (out[i + 1].pos - out[i].pos || 1));
    return p < out[0].pos ? out[0].color : out[out.length - 1].color;
  };
  const inside = out.filter((s) => s.pos >= 0 && s.pos <= 100);
  if (out[0].pos < 0) inside.unshift({ color: at(0), pos: 0 });
  if (out[out.length - 1].pos > 100) inside.push({ color: at(100), pos: 100 });
  return inside;
};
const ktStops = ([head, ...stops]) => {
  const parsed = clampStops(stops).map(({ color, pos }) => `${+(pos / 100).toFixed(4)}f to ${ktColor(color)}`).join(', ');
  const r = /^radial\s+([\d.]+)%\s+([\d.]+)%\s+at\s+([\d.]+)%\s+([\d.]+)%$/.exec(head);
  if (r) return `EqualGradientSpec(angle = 0f, stops = listOf(${parsed}), radial = EqualRadial(${r.slice(1).map((n) => `${+(parseFloat(n) / 100).toFixed(4)}f`).join(', ')}))`;
  return `EqualGradientSpec(angle = ${parseFloat(head)}f, stops = listOf(${parsed}))`;
};
const weightName = (w) => ({ 400: 'FontWeight.W400', 500: 'FontWeight.W500', 700: 'FontWeight.W700' })[w];

const kt = `// ${HEADER}
@file:Suppress("unused", "MemberVisibilityCanBePrivate")

package ai.equal.ds.tokens

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.em
import androidx.compose.ui.unit.sp

/** Raw colour values. Never use directly in UI — go through [EqualColors]. */
object EqualPrimitives {
${Object.entries(prim).map(([k, hex]) => `    val ${k.split('.')[1]} = ${ktColor(hex)}`).join('\n')}
}

/** Semantic colour tokens. Resolves per theme (see [LightEqualColors] / [DarkEqualColors]). */
@Immutable
data class EqualColors(
${aliases.map((a) => `    /** ${a.name}${a.derived ? ' — derived from the screens' : ''} */\n    val ${a.key}: Color,`).join('\n')}
    val isDark: Boolean,
)

val LightEqualColors = EqualColors(
${aliases.map((a) => `    ${a.key} = ${ktColor(a.light)}, // ${a.lightRef}`).join('\n')}
    isDark = false,
)

val DarkEqualColors = EqualColors(
${aliases.map((a) => `    ${a.key} = ${ktColor(a.dark)}, // ${a.darkRef}`).join('\n')}
    isDark = true,
)

/** Elliptical radial gradient: radii and centre as fractions of the painted size (CSS radial-gradient(rx ry at cx cy)). */
@Immutable
data class EqualRadial(val radiusX: Float, val radiusY: Float, val centerX: Float, val centerY: Float)

/** Gradient: linear (CSS-style angle: 0 = to top, 90 = to right, 180 = to bottom) or, with [radial], elliptical radial. */
@Immutable
data class EqualGradientSpec(val angle: Float, val stops: List<Pair<Float, Color>>, val radial: EqualRadial? = null)

@Immutable
data class EqualGradients(
${gradients.map((g) => `    val ${g.key}: EqualGradientSpec,`).join('\n')}
)

val LightEqualGradients = EqualGradients(
${gradients.map((g) => `    ${g.key} = ${ktStops(g.light)},`).join('\n')}
)

val DarkEqualGradients = EqualGradients(
${gradients.map((g) => `    ${g.key} = ${ktStops(g.dark)},`).join('\n')}
)

/** Twelve type tokens (+ captionWrap, body1Italic, badgeCount). Font family is applied by EqualTheme. */
object EqualTypeTokens {
    private val T = (${t.typography.$tracking.default}).em      // system default
    private val T_11 = ${t.typography.$tracking.overline}.em     // uppercase at 11sp
    private val T_10 = ${t.typography.$tracking.badge}.em     // uppercase at 10sp
    private const val TNUM = "tnum"

${typeEntries
  .map(([name, s]) => {
    const tracking = s.tracking === t.typography.$tracking.overline ? 'T_11' : s.tracking === t.typography.$tracking.badge ? 'T_10' : 'T';
    const extra = [s.italic ? 'fontStyle = FontStyle.Italic' : null, s.tabular ? 'fontFeatureSettings = TNUM' : null].filter(Boolean);
    return `    val ${name} = TextStyle(fontSize = ${s.size}.sp, lineHeight = ${s.lineHeight}.sp, fontWeight = ${weightName(s.weight)}, letterSpacing = ${tracking}${extra.length ? ', ' + extra.join(', ') : ''})${s.uppercase ? ' // uppercase the string, not the renderer' : ''}`;
  })
  .join('\n')}
}

object EqualSpacing {
${Object.entries(t.spacing).map(([k, v]) => `    val s${k} = ${v}.dp`).join('\n')}
}

object EqualRadius {
${Object.entries(t.radius).map(([k, v]) => `    val ${k === 'full' ? 'full' : 'r' + k.charAt(0).toUpperCase() + k.slice(1)} = ${v}.dp`).join('\n')}
}

object EqualSize {
    val touchTarget = ${t.size.touchTarget}.dp
    val statusBar = ${t.size.statusBar}.dp
    val appBar = ${t.size.appBar}.dp
${Object.entries(t.size.icon).map(([k, v]) => `    val icon${k.toUpperCase()} = ${v}.dp`).join('\n')}
${Object.entries(t.size.avatar).map(([k, v]) => `    val avatar${k.toUpperCase()} = ${v}.dp`).join('\n')}
}

object EqualMotion {
${Object.entries(t.motion.duration).map(([k, v]) => `    const val ${k} = ${v}`).join('\n')}
}
`;

const out = (p, s) => {
  const full = resolve(root, p);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, s);
  console.log('  wrote', p);
};
out('web/src/tokens/tokens.css', css);
out('web/src/tokens/tokens.ts', ts);
out('compose/equal-ds/src/main/java/ai/equal/ds/tokens/EqualTokens.kt', kt);
